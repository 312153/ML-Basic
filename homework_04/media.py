def examples() -> None:
    """Демонстрация типового пользовательского кода над иерархией."""

    # CREATE: аудио-трек на локальном диске
    track = LocalAudioFile(
        name="song.mp3",
        duration=212.0,
        bitrate=320,
        sample_rate=44_100,
        owner="alex",
    )
    track.save()  # записать файл и метаданные в хранилище

    # UPDATE: сменили владельца — метаданные обновляются и пересохраняются
    track.update_metadata(owner="aleksander")

    # ДЕЙСТВИЕ: конвертация и извлечение фич (тип-специфичные операции)
    track.convert("flac")
    track.extract_features()

    # Тот же тип, но другое хранилище — клиентский код почти не меняется:
    clip = S3VideoFile(
        name="clip.mp4",
        duration=15.0,
        resolution=(1920, 1080),
        codec="h264",
        fps=30.0,
        owner="alex",
    )
    clip.save()
    thumb = clip.extract_thumbnail(at_second=2.0)  # вернёт объект-изображение
    if thumb is not None:
        thumb.save()

    # DELETE: удалить файл из хранилища
    track.delete()


